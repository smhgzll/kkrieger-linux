#!/usr/bin/env python3
"""shaderpack.py SHADERDIR OUT_SHADERS.inc OUT_MATERIALS.inc

Packs the GLSL shaders of port/src/shaders for the executable:

* the shader text, minified (comments and needless white space removed),
  NUL separated; the driver compiles it at start (glCreateShaderProgramv).
  Order: mat_vs*.vert, then mat_ps*.frag, sorted by name.
* the material table from materials.txt: hash of the material key ->
  vertex/pixel shader index (see the key in material11.cpp)."""
import glob, os, re, sys

SRC, OUT_SHADERS, OUT_MATERIALS = sys.argv[1:4]

TOKEN = re.compile(r'#[^\n]*|[A-Za-z_][A-Za-z0-9_]*|\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?'
                   r'|\+\+|--|<<|>>|<=|>=|==|!=|&&|\|\||[-+*/%&|^]=|\S')
MULTI = {'++', '--', '<<', '>>', '<=', '>=', '==', '!=', '&&', '||', '+=', '-=', '*=', '/=', '//', '/*'}

def minify(text):
    text = re.sub(r'//[^\n]*', '', text)
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    out = ''
    for tok in TOKEN.findall(text):
        if tok.startswith('#'):                    # preprocessor lines keep their line
            out += ('\n' if out else '') + ' '.join(tok.split()) + '\n'
            continue
        if out and not out.endswith('\n'):
            a, b = out[-1], tok[0]
            word = lambda c: c.isalnum() or c == '_'
            if (word(a) and word(b)) or (a + b) in MULTI or (a in '+-' and b in '+-') or (a == '.' and b.isdigit()):
                out += ' '
        out += tok
    return out

# shorter names: the stages are separate programs and match by location
RENAME = {'VSConstants': 'U', 'PSConstants': 'U', 'inPosition': 'p', 'inNormal': 'n', 'inColor0': 'i',
          'inColor1': 'j', 'inTangent': 'g', 'inBinormal': 'h', 'outColor0': 'd0', 'outColor1': 'd1',
          'outColor': 'o', 'oPos': 'q', **{'inTexCoord%d' % i: 'u%d' % i for i in range(4)},
          **{'outTexCoord%d' % i: 'v%d' % i for i in range(4)}, **{'tex%d' % i: 's%d' % i for i in range(4)}}

def shorten(text):
    text = re.sub(r'(?<![.\w])([A-Za-z_]\w*)\b', lambda m: RENAME.get(m.group(1), m.group(1)), text)
    for k in re.findall(r'const vec4 (k\d+)=', text):      # constants nothing reads
        if len(re.findall(r'\b%s\b' % k, text)) == 1:
            text = re.sub(r'const vec4 %s=vec4\([^)]*\);' % k, '', text)
    return text

files = sorted(glob.glob(os.path.join(SRC, 'mat_vs*.vert')))
nvs = len(files)
files += sorted(glob.glob(os.path.join(SRC, 'mat_ps*.frag')))
texts = [shorten(minify(open(f).read())) for f in files]

def cstring(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return '"%s\\0"' % s

keys = []
for line in open(os.path.join(SRC, 'materials.txt')):
    line = line.split('#')[0].split()
    if not line: continue
    h = 2166136261                                 # FNV-1a over the key words
    for w in (int(x, 16) for x in line[:-2]):
        h = ((h ^ w) * 16777619) & 0xffffffff
    keys.append((h, int(line[-2]), nvs + int(line[-1])))
assert len(set(k[0] for k in keys)) == len(keys), 'material key hash collision'

def array(name, ctype, values, per_line=8, fmt='0x%08x'):
    lines = ['static const %s %s[%d] =' % (ctype, name, len(values)), '{']
    for i in range(0, len(values), per_line):
        lines.append('  ' + ','.join(fmt % v for v in values[i:i + per_line]) + ',')
    return '\n'.join(lines + ['};', ''])

hdr = '// generated by tools/shaderpack.py from port/src/shaders: do not edit\n\n'
with open(OUT_SHADERS, 'w') as f:
    f.write(hdr + '#define SHADER_COUNT %d\n#define SHADER_VS %d   // vertex shaders first\n\n' % (len(files), nvs))
    f.write('static const char ShaderText[] =\n')
    for path, t in zip(files, texts):
        f.write('  // %s\n  %s\n' % (os.path.basename(path), cstring(t)))
    f.write(';\n')
with open(OUT_MATERIALS, 'w') as f:
    f.write(hdr + '#define MATERIAL_SHADERS %d\n\n' % len(keys))
    f.write(array('MaterialShaderKey', 'sU32', [k[0] for k in keys]))
    f.write(array('MaterialShaderVS', 'sU8', [k[1] for k in keys], 16, '%d'))
    f.write(array('MaterialShaderPS', 'sU8', [k[2] for k in keys], 16, '%d'))
print('shaderpack: %d shaders (%d bytes of GLSL), %d materials' % (len(files), sum(len(t) + 1 for t in texts), len(keys)))
