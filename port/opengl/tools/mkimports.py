#!/usr/bin/env python3
"""mkimports.py EXE OUT.asm LIB.so...

Import by hash for the size build. EXE is the program linked the normal
way; its undefined dynamic symbols are the imports. OUT.asm gets, per
import, a jump through ImportTable (functions) or a variable the resolver
copies (data), and the GNU hash of each name. linux/imports.cpp fills the
table at start from the GNU hash tables of the loaded libraries, so the
executable carries no symbol names, symbol table, PLT or version tables.
The LIBs (the real libraries) are used to tell data from functions and to
check that no other exported name has the same hash."""
import os, re, subprocess, sys

if sys.argv[1] == '--stubs':
    # mkimports.py --stubs EXE DIR CXX: an empty library per DT_NEEDED of EXE
    # (only the soname), DIR/list = their paths in load order for the link
    EXE, DIR, CXX = sys.argv[2:5]
    os.makedirs(DIR, exist_ok=True)
    needed = re.findall(r'\(NEEDED\).*\[(.*)\]', subprocess.run(['readelf', '-d', EXE], capture_output=True,
                                                                  text=True, check=True).stdout)
    for lib in needed:
        subprocess.run([CXX, '-m32', '-shared', '-nostdlib', '-Wl,-soname,' + lib, '-o', os.path.join(DIR, lib),
                        '-x', 'c', '/dev/null'], check=True)
    open(os.path.join(DIR, 'list'), 'w').write('\n'.join(os.path.join(DIR, l) for l in needed) + '\n')
    sys.exit(0)

EXE, OUT, LIBS = sys.argv[1], sys.argv[2], sys.argv[3:]

def gnuhash(name):
    h = 5381
    for c in name.encode():
        h = (h * 33 + c) & 0xffffffff
    return h

def dynsyms(path):
    out = subprocess.run(['readelf', '-W', '--dyn-syms', path], capture_output=True, text=True, check=True).stdout
    for line in out.split('\n'):
        f = line.split()
        if len(f) >= 8 and f[0].endswith(':') and f[6] != 'UND':
            yield f[7].split('@')[0], f[3]

names = []
for line in subprocess.run(['nm', '-D', '--undefined-only', EXE], capture_output=True, text=True, check=True).stdout.split('\n'):
    if line.strip():
        names.append(line.split()[-1].split('@')[0])
relocs = subprocess.run(['readelf', '-W', '-r', EXE], capture_output=True, text=True, check=True).stdout
names += [m.split('@')[0] for m in re.findall(r'R_386_COPY\s+\S+\s+(\S+)', relocs)]   # data copied into EXE
names = sorted(set(names) - {'__gmon_start__', '_ITM_deregisterTMCloneTable', '_ITM_registerTMCloneTable'})

types, exported = {}, {}
for lib in LIBS:
    for name, typ in dynsyms(lib):
        types.setdefault(name, typ)
        exported.setdefault(gnuhash(name), set()).add(name)
for n in names:
    if n not in types: sys.exit('mkimports: %s is not in the given libraries' % n)
    if exported[gnuhash(n)] != {n}: sys.exit('mkimports: hash of %s collides with %s' % (n, exported[gnuhash(n)]))

funcs = [n for n in names if types[n] != 'OBJECT']
data = [n for n in names if types[n] == 'OBJECT']
order = funcs + data
with open(OUT, 'w') as f:
    f.write('; generated by tools/mkimports.py: do not edit\n                bits    32\n')
    f.write('                section .text\n')
    for i, n in enumerate(funcs):
        f.write('                global  %s\n%s: jmp [ImportTable+%d]\n' % (n, n, 4 * i))
    f.write('                section .rodata\n                global  ImportHashes,ImportCount,ImportData\n')
    f.write('ImportCount:    dd      %d\n' % len(order))
    f.write('ImportHashes:   dd      %s\n' % ','.join('0x%08x' % gnuhash(n) for n in order))
    f.write('ImportData:     dd      %s\n' % ','.join(['%d,%s' % (len(funcs) + i, n) for i, n in enumerate(data)] + ['-1']))
    f.write('                section .bss\n                global  ImportTable\nImportTable:    resd    %d\n' % len(order))
    for n in data:
        f.write('                global  %s\n%s:   resd    1\n' % (n, n))
print('mkimports: %d functions, %d data' % (len(funcs), len(data)))
